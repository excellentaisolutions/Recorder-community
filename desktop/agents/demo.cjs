const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { transcode } = require('./media.cjs');

const { executeStep } = require('./demo-steps.cjs');

async function runDemo(app, storage, recipe, allowed) {
  process.env.PLAYWRIGHT_BROWSERS_PATH = app.isPackaged ? path.join(process.resourcesPath, 'playwright') : path.join(app.getAppPath(), 'bin', 'playwright');
  const { chromium } = require('playwright');
  const directory = storage.getConfig().outputDir;
  const work = path.join(directory, `.demo-${crypto.randomUUID()}`);
  fs.mkdirSync(work);
  let browser, context, page, video, artifact, failure;
  const marks = [], screenshots = [], steps = [];
  let started;
  const guard = () => { if (!allowed()) throw new Error('Demo cancelada: acceso revocado o cancelación solicitada.'); };
  let cancelling = false;
  const cancelTimer = setInterval(() => {
    if (!allowed() && page && !cancelling) { cancelling = true; context.close().catch(() => {}); }
  }, 250);
  try {
    guard();
    browser = await chromium.launch({ channel: recipe.browser, headless: false });
    guard();
    context = await browser.newContext({ viewport: { width: recipe.width, height: recipe.height },
      recordVideo: { dir: work, size: { width: recipe.width, height: recipe.height } }, acceptDownloads: false });
    guard();
    page = await context.newPage();
    page.setDefaultTimeout(10000);
    video = page.video();
    guard();
    started = performance.now();
    await page.goto(recipe.url, { waitUntil: 'domcontentloaded', timeout: 30000 });
    for (let index = 0; index < recipe.steps.length; index++) {
      guard();
      const step = recipe.steps[index];
      try {
        await executeStep(page, step, { storage, width: recipe.width, height: recipe.height, started, guard, marks, screenshots });
        steps.push({ index, action: step.action, status: 'completed' });
      } catch (error) { throw new Error(`Paso ${index + 1} (${step.action}) falló: ${error.message}`); }
    }
    guard();
  } catch (error) { failure = error; }
  finally {
    clearInterval(cancelTimer);
    await context?.close().catch(() => {});
    if (video) {
      const output = storage.freshPath('webm');
      try { await video.saveAs(output); artifact = storage.fileEntry(output); } catch (error) { failure ||= error; }
    }
    await browser?.close().catch(() => {});
    // Only scratch videos generated by this run live in this UUID directory.
    if (path.dirname(path.resolve(work)) === path.resolve(directory) && path.basename(work).startsWith('.demo-')) fs.rmSync(work, { recursive: true, force: true });
  }
  if (failure) throw new Error(`${failure.message}${artifact ? `. Grabación parcial conservada: ${artifact.path}` : ''}`);
  if (!artifact?.size) throw new Error('La demo no produjo vídeo.');
  if (recipe.format === 'mp4') {
    const output = storage.freshPath('mp4');
    await transcode(app, ['-i', artifact.path, '-c:v', 'libx264', '-preset', 'veryfast', '-pix_fmt', 'yuv420p', '-movflags', '+faststart', output], allowed);
    artifact = storage.fileEntry(output);
  }
  const result = { title: recipe.title, artifact, marks, screenshots, steps,
    capture: 'browser-viewport', audio: false };
  fs.writeFileSync(`${artifact.path}.demo.json`, JSON.stringify(result, null, 2));
  return result;
}
module.exports = { runDemo };
